
alphabet_map = {
    " ": 0x00, "A": 0x01, "B": 0x02, "C": 0x03, "D": 0x04,
    "E": 0x05, "F": 0x06, "G": 0x07, "H": 0x08, "I": 0x09,
    "J": 0x0A, "K": 0x0B, "L": 0x0C, "M": 0x0D, "N": 0x0E,
    "O": 0x0F, "P": 0x10, "Q": 0x11, "R": 0x12, "S": 0x13,
    "T": 0x14, "U": 0x15, "V": 0x16, "W": 0x17, "X": 0x18,
    "Y": 0x19, "Z": 0x1A, "1": 0x1B, "2": 0x1C, "3": 0x1D,
    "4": 0x1E, "5": 0x1F, "6": 0x20, "7": 0x21, "8": 0x22,
    "9": 0x23, "0": 0x24,
}

def string_to_hex_list(string: str):
    string = string.upper().strip('"')
    return [alphabet_map[char] for char in string]
